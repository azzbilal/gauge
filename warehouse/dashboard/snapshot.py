"""Query the three marts in gauge.duckdb and write a JSON snapshot for the static dashboard.

Writes two files next to index.html:
  snapshot.json  the data (for scripts, diffing, or serving over http)
  snapshot.js    the same data as `window.GAUGE_SNAPSHOT = {...}`, so index.html also
                 works when opened straight from disk (browsers block fetch() on file://)

Opens the database read-only. Run after the warehouse is built (run.py or the Dagster job):

    python warehouse/dashboard/snapshot.py [--db PATH] [--out DIR]
"""
from __future__ import annotations

import argparse
import datetime as dt
import decimal
import json
import os
from pathlib import Path

import duckdb

HERE = Path(__file__).resolve().parent
DEFAULT_DB = HERE.parent / "gauge.duckdb"

# name -> (title, query). Column order in each query is the order shown on the dashboard:
# the headline metrics come right after the name, the counts behind them follow.
MARTS = {
    "mart_campaign": (
        "Campaigns",
        """
        select campaign_name, task_count, accept_rate, reviewer_agreement, tasks_per_day,
               target_count, gold_task_count, accepted_count, rejected_count,
               multi_reviewed_count, agreed_count, active_days
        from main_marts.mart_campaign
        order by task_count desc, campaign_name
        """,
    ),
    "mart_task_quality": (
        "Task quality by criterion",
        """
        select criterion, avg_score, avg_score_accepted, avg_score_rejected, share_with_evidence,
               acceptance_min, n_tasks, n_scores, n_with_evidence, n_legacy_scores
        from main_marts.mart_task_quality
        order by criterion_order
        """,
    ),
    "mart_reviewer_calibration": (
        "Reviewer calibration (gold)",
        """
        select reviewer_name, reviewer_expert_id, n_gold_reviews, gold_accuracy,
               false_accept_rate, false_reject_rate, flagged_for_recalibration,
               n_reviews, n_task_reviews, n_gold_unscorable, n_gold_correct,
               n_gold_bad, n_false_accepts, n_gold_good, n_false_rejects
        from main_marts.mart_reviewer_calibration
        order by n_reviews desc, reviewer_name
        """,
    ),
}


def _json_default(value):
    if isinstance(value, decimal.Decimal):
        return float(value)
    if isinstance(value, (dt.datetime, dt.date)):
        return value.isoformat()
    raise TypeError(f"not JSON serialisable: {type(value).__name__}")


def build_snapshot(db_path: Path) -> dict:
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        loaded_at, table_counts = con.execute(
            "select loaded_at, table_counts from raw._load_log"
        ).fetchone()
        marts = {}
        for name, (title, sql) in MARTS.items():
            cur = con.execute(sql)
            columns = [d[0] for d in cur.description]
            marts[name] = {"title": title, "columns": columns, "rows": [list(r) for r in cur.fetchall()]}
    finally:
        con.close()
    return {
        "generated_at": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "loaded_at": loaded_at,
        "raw_table_counts": table_counts,
        "database": db_path.name,
        "marts": marts,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--db", type=Path, default=Path(os.environ.get("GAUGE_DUCKDB_PATH", DEFAULT_DB)))
    ap.add_argument("--out", type=Path, default=HERE)
    args = ap.parse_args()

    snap = build_snapshot(args.db.resolve())
    text = json.dumps(snap, default=_json_default, indent=2, ensure_ascii=False)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "snapshot.json").write_text(text + "\n", encoding="utf-8")
    (args.out / "snapshot.js").write_text(
        "// Generated by snapshot.py; do not edit.\nwindow.GAUGE_SNAPSHOT = " + text + ";\n",
        encoding="utf-8",
    )
    for name, mart in snap["marts"].items():
        print(f"snapshot: {name:<26} {len(mart['rows']):>3} rows")
    print(f"snapshot: wrote {args.out / 'snapshot.json'} (+ snapshot.js)")


if __name__ == "__main__":
    main()
